-- Split bookable room types from numbered physical rooms and add a room-service
-- folio. GHS is the charge currency; the room's USD price is display-only.
create table if not exists public.room_units (
  id bigint generated by default as identity primary key,
  room_type_id bigint not null references public.rooms(id) on delete cascade,
  room_number text not null unique,
  qr_token uuid not null default gen_random_uuid() unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (room_type_id, room_number)
);

-- Preserve the existing inventory count while the hotel replaces these
-- temporary labels with its real room numbers in /admin/rooms.
insert into public.room_units(room_type_id, room_number)
select r.id, 'TEMP-' || r.id::text || '-' || series.unit_number::text
from public.rooms r
cross join lateral generate_series(1, r.inventory_count) as series(unit_number)
on conflict (room_type_id, room_number) do nothing;

alter table public.reservations
  add column if not exists room_unit_id bigint references public.room_units(id) on delete restrict,
  add column if not exists checked_in_at timestamptz,
  add column if not exists checked_out_at timestamptz,
  add column if not exists room_order_token_hash text;

create index if not exists reservations_room_unit_dates_idx
  on public.reservations(room_unit_id, start_date, end_date)
  where room_unit_id is not null and deleted_at is null;

alter table public.reservations
  drop constraint if exists no_overlapping_room_unit_reservations;
alter table public.reservations
  add constraint no_overlapping_room_unit_reservations
  exclude using gist (room_unit_id with =, daterange(start_date, end_date, '[)') with &&)
  where (room_unit_id is not null and status in ('pending', 'confirmed')
    and deleted_at is null and checked_out_at is null);

alter table public.room_units enable row level security;
revoke all on public.room_units from anon, authenticated;
grant all on public.room_units to service_role;

create or replace function public.set_room_type_units(
  p_room_type_id bigint,
  p_room_numbers text[]
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  room_type public.rooms;
  normalized_numbers text[];
  number_count integer;
begin
  select * into room_type from public.rooms where id = p_room_type_id for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'ROOM_NOT_FOUND'); end if;

  select array_agg(trim(numbers.number) order by trim(numbers.number)) into normalized_numbers
  from unnest(coalesce(p_room_numbers, array[]::text[])) as numbers(number)
  where trim(numbers.number) <> '';
  number_count := coalesce(cardinality(normalized_numbers), 0);
  if number_count < 1 or number_count > 500
     or number_count <> (select count(distinct numbers.number) from unnest(normalized_numbers) as numbers(number))
     or exists (select 1 from unnest(normalized_numbers) as numbers(number)
                where length(numbers.number) > 24 or numbers.number !~ '^[[:alnum:]][[:alnum:][:space:]-]{0,23}$') then
    return jsonb_build_object('ok', false, 'code', 'INVALID_ROOM_NUMBERS');
  end if;

  if exists (
    select 1 from public.room_units u
    join public.reservations r on r.room_unit_id = u.id
    where u.room_type_id = p_room_type_id and u.is_active
      and not (u.room_number = any(normalized_numbers))
      and r.status = 'confirmed' and r.checked_out_at is null and r.deleted_at is null
  ) then
    return jsonb_build_object('ok', false, 'code', 'ROOM_IN_USE');
  end if;

  update public.room_units u set is_active = false, updated_at = now()
  where u.room_type_id = p_room_type_id and u.is_active
    and not (u.room_number = any(normalized_numbers));

  update public.room_units u set is_active = true, updated_at = now()
  where u.room_type_id = p_room_type_id and u.room_number = any(normalized_numbers);

  insert into public.room_units(room_type_id, room_number)
  select p_room_type_id, numbers.number from unnest(normalized_numbers) as numbers(number)
  where not exists (
    select 1 from public.room_units u
    where u.room_type_id = p_room_type_id and u.room_number = numbers.number
  );

  update public.rooms r set inventory_count = number_count, updated_at = now()
  where r.id = p_room_type_id;

  return jsonb_build_object('ok', true, 'inventory_count', number_count);
exception when unique_violation then
  return jsonb_build_object('ok', false, 'code', 'ROOM_NUMBER_IN_USE');
end;
$$;
revoke all on function public.set_room_type_units(bigint,text[]) from public, anon, authenticated;
grant execute on function public.set_room_type_units(bigint,text[]) to service_role;

create or replace function public.check_in_reservation(
  p_reservation_id bigint,
  p_room_unit_id bigint,
  p_room_order_token_hash text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare stay public.reservations;
begin
  select * into stay from public.reservations where id = p_reservation_id for update;
  if not found or stay.status <> 'confirmed' or stay.checked_out_at is not null
     or stay.start_date > current_date or stay.end_date <= current_date then
    return jsonb_build_object('ok', false, 'code', 'NOT_CHECKIN_ELIGIBLE');
  end if;
  if length(coalesce(p_room_order_token_hash, '')) <> 64 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_ORDER_TOKEN');
  end if;
  if not exists (
    select 1 from public.room_units u
    where u.id = p_room_unit_id and u.room_type_id = stay.room_id and u.is_active
  ) then
    return jsonb_build_object('ok', false, 'code', 'INVALID_ROOM_UNIT');
  end if;
  update public.reservations set room_unit_id = p_room_unit_id,
    checked_in_at = now(), room_order_token_hash = p_room_order_token_hash,
    updated_at = now()
  where id = p_reservation_id returning * into stay;
  return jsonb_build_object('ok', true, 'reservation_id', stay.id,
    'room_unit_id', stay.room_unit_id, 'checked_in_at', stay.checked_in_at);
exception when exclusion_violation then
  return jsonb_build_object('ok', false, 'code', 'ROOM_UNIT_UNAVAILABLE');
end;
$$;
revoke all on function public.check_in_reservation(bigint,bigint,text) from public, anon, authenticated;
grant execute on function public.check_in_reservation(bigint,bigint,text) to service_role;

create table if not exists public.room_service_products (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 2 and 120),
  description text not null default '' check (length(description) <= 1000),
  price_ghs numeric(10,2) not null check (price_ghs >= 0),
  price_usd numeric(10,2) check (price_usd is null or price_usd >= 0),
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.room_service_orders (
  id bigint generated by default as identity primary key,
  reservation_id bigint not null references public.reservations(id) on delete restrict,
  room_unit_id bigint not null references public.room_units(id) on delete restrict,
  guest_id bigint not null references public.guests(id) on delete restrict,
  status text not null default 'new'
    check (status in ('new', 'accepted', 'preparing', 'delivered', 'cancelled')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid', 'paid')),
  payment_method text check (payment_method is null or payment_method in ('cash', 'momo_transfer', 'pos_card')),
  total_ghs numeric(10,2) not null check (total_ghs >= 0),
  guest_note text not null default '' check (length(guest_note) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  paid_at timestamptz
);

create table if not exists public.room_service_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.room_service_orders(id) on delete cascade,
  product_id bigint not null references public.room_service_products(id) on delete restrict,
  product_name text not null,
  quantity integer not null check (quantity between 1 and 20),
  unit_price_ghs numeric(10,2) not null check (unit_price_ghs >= 0),
  line_total_ghs numeric(10,2) not null check (line_total_ghs >= 0)
);

create index if not exists room_service_orders_status_created_idx
  on public.room_service_orders(status, created_at desc);
create index if not exists room_service_orders_reservation_idx
  on public.room_service_orders(reservation_id, payment_status, status);

alter table public.room_service_products enable row level security;
alter table public.room_service_orders enable row level security;
alter table public.room_service_order_items enable row level security;
revoke all on public.room_service_products, public.room_service_orders, public.room_service_order_items from anon, authenticated;
grant all on public.room_service_products, public.room_service_orders, public.room_service_order_items to service_role;

create or replace function public.submit_room_service_order(
  p_room_unit_id bigint,
  p_room_order_token_hash text,
  p_items jsonb,
  p_guest_note text default ''
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  stay public.reservations;
  created_order public.room_service_orders;
  item record;
  product public.room_service_products;
  total numeric(10,2) := 0;
  line_total numeric(10,2);
  item_count integer;
begin
  select * into stay from public.reservations r
  where r.room_unit_id = p_room_unit_id
    and r.room_order_token_hash = p_room_order_token_hash
    and r.checked_in_at is not null and r.checked_out_at is null
    and r.status = 'confirmed' and r.deleted_at is null
    and r.start_date <= current_date and r.end_date > current_date
  for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'INVALID_STAY_ACCESS'); end if;
  if jsonb_typeof(p_items) <> 'array' then
    return jsonb_build_object('ok', false, 'code', 'INVALID_ITEMS');
  end if;
  select count(*) into item_count from jsonb_array_elements(p_items);
  if item_count < 1 or item_count > 20 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_ITEMS');
  end if;

  insert into public.room_service_orders(reservation_id, room_unit_id, guest_id, guest_note, total_ghs)
  values (stay.id, p_room_unit_id, stay.guest_id, left(coalesce(p_guest_note, ''), 500), 0)
  returning * into created_order;

  for item in select * from jsonb_to_recordset(p_items) as x(product_id bigint, quantity integer)
  loop
    if item.product_id is null or item.quantity is null or item.quantity < 1 or item.quantity > 20 then
      raise exception 'Invalid room service item quantity.' using errcode = '22023';
    end if;
    select * into product from public.room_service_products p
    where p.id = item.product_id and p.is_available for share;
    if not found then
      delete from public.room_service_orders where id = created_order.id;
      return jsonb_build_object('ok', false, 'code', 'PRODUCT_UNAVAILABLE');
    end if;
    line_total := round(product.price_ghs * item.quantity, 2);
    total := total + line_total;
    insert into public.room_service_order_items(
      order_id, product_id, product_name, quantity, unit_price_ghs, line_total_ghs
    ) values (
      created_order.id, product.id, product.name, item.quantity, product.price_ghs, line_total
    );
  end loop;

  update public.room_service_orders set total_ghs = total, updated_at = now()
  where id = created_order.id;
  return jsonb_build_object('ok', true, 'order_id', created_order.id, 'total_ghs', total);
end;
$$;
revoke all on function public.submit_room_service_order(bigint,text,jsonb,text) from public, anon, authenticated;
grant execute on function public.submit_room_service_order(bigint,text,jsonb,text) to service_role;

create or replace function public.update_room_service_order_status(
  p_order_id bigint,
  p_status text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare old_status text;
begin
  select status into old_status from public.room_service_orders where id = p_order_id for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'ORDER_NOT_FOUND'); end if;
  if not (
    (old_status = 'new' and p_status in ('accepted', 'cancelled')) or
    (old_status = 'accepted' and p_status in ('preparing', 'cancelled')) or
    (old_status = 'preparing' and p_status in ('delivered', 'cancelled'))
  ) then return jsonb_build_object('ok', false, 'code', 'INVALID_ORDER_TRANSITION'); end if;
  update public.room_service_orders set status = p_status, updated_at = now() where id = p_order_id;
  return jsonb_build_object('ok', true);
end;
$$;
revoke all on function public.update_room_service_order_status(bigint,text) from public, anon, authenticated;
grant execute on function public.update_room_service_order_status(bigint,text) to service_role;

create or replace function public.checkout_room_stay(
  p_reservation_id bigint,
  p_payment_method text default null
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  stay public.reservations;
  amount_due numeric(10,2);
begin
  select * into stay from public.reservations where id = p_reservation_id for update;
  if not found or stay.checked_in_at is null or stay.checked_out_at is not null
     or stay.status <> 'confirmed' then
    return jsonb_build_object('ok', false, 'code', 'NOT_CHECKOUT_ELIGIBLE');
  end if;
  if exists (select 1 from public.room_service_orders o
             where o.reservation_id = stay.id and o.status in ('new', 'accepted', 'preparing')) then
    return jsonb_build_object('ok', false, 'code', 'ORDERS_STILL_IN_PROGRESS');
  end if;
  select coalesce(sum(o.total_ghs), 0) into amount_due
  from public.room_service_orders o
  where o.reservation_id = stay.id and o.status = 'delivered' and o.payment_status = 'unpaid';
  if amount_due > 0 and coalesce(p_payment_method, '') not in ('cash', 'momo_transfer', 'pos_card') then
    return jsonb_build_object('ok', false, 'code', 'PAYMENT_METHOD_REQUIRED', 'amount_due', amount_due);
  end if;

  update public.room_service_orders set payment_status = 'paid',
    payment_method = p_payment_method, paid_at = now(), updated_at = now()
  where reservation_id = stay.id and status = 'delivered' and payment_status = 'unpaid';
  update public.reservations set status = 'finished', checked_out_at = now(),
    room_order_token_hash = null, updated_at = now()
  where id = stay.id;
  return jsonb_build_object('ok', true, 'amount_collected', amount_due, 'reservation_id', stay.id);
end;
$$;
revoke all on function public.checkout_room_stay(bigint,text) from public, anon, authenticated;
grant execute on function public.checkout_room_stay(bigint,text) to service_role;
