-- Keep the reservation row focused on stay lifecycle and record payment attempts
-- separately. Existing payment details are preserved as legacy transaction rows.
create table if not exists public.reservation_transactions (
  id bigint generated by default as identity primary key,
  reservation_id bigint not null references public.reservations(id) on delete restrict,
  provider text not null check (provider in ('paystack', 'manual', 'stripe', 'other')),
  provider_reference text unique,
  provider_transaction_id text,
  transaction_type text not null default 'charge' check (transaction_type in ('charge', 'refund')),
  amount_minor bigint not null check (amount_minor >= 0),
  currency text not null default 'GHS',
  method text,
  recorded_by text,
  status text not null default 'pending' check (status in ('pending', 'success', 'failed', 'legacy', 'refund_pending', 'refunded')),
  verified_at timestamptz,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists reservation_transactions_reservation_idx
  on public.reservation_transactions(reservation_id, created_at desc);
create index if not exists reservation_transactions_status_idx
  on public.reservation_transactions(status, created_at desc);
alter table public.reservation_transactions enable row level security;
revoke all on public.reservation_transactions from public, anon, authenticated;
grant all on public.reservation_transactions to service_role;

-- Preserve old references and amounts. Historic online confirmations are labeled
-- legacy because the old schema did not record which confirmation path verified them.
insert into public.reservation_transactions
  (reservation_id, provider, provider_reference, transaction_type, amount_minor, currency, method, status, paid_at)
select r.id,
       case when r.stripe_session_id is not null then 'stripe'
            when r.booking_source = 'walk_in' then 'manual'
            when r.payment_provider = 'paystack' or r.payment_method = 'paystack' then 'paystack'
            else 'other' end,
       coalesce(r.payment_reference, r.stripe_session_id),
       'charge', round(r.reserved_price * 100)::bigint, coalesce(r.currency, 'GHS'),
       r.payment_method,
       case when r.status = 'pending' then 'pending'
            when r.status = 'confirmed' and r.booking_source = 'walk_in' then 'success'
            else 'legacy' end,
       case when r.status = 'confirmed' and r.booking_source = 'walk_in' then r.created_at else null end
from public.reservations r
where r.payment_reference is not null or r.stripe_session_id is not null or r.payment_method is not null
on conflict (provider_reference) do nothing;

alter table public.payment_exceptions add column if not exists transaction_id bigint
  references public.reservation_transactions(id) on delete set null;
update public.payment_exceptions e set transaction_id = t.id
from public.reservation_transactions t
where e.transaction_id is null and e.payment_reference = t.provider_reference;

-- The RPC remains service-role-only. Reservation insertion and transaction creation
-- are atomic, including walk-in payments recorded at the desk.
drop function if exists public.claim_room_reservation(bigint,bigint,integer,date,date,numeric,text,text,text,text,text,text);
create function public.claim_room_reservation(
  p_room_id bigint, p_guest_id bigint, p_guests_count integer,
  p_start_date date, p_end_date date, p_reserved_price numeric,
  p_currency text default 'GHS', p_message text default '',
  p_status text default 'pending', p_booking_source text default 'online',
  p_payment_method text default null, p_payment_reference text default null,
  p_recorded_by text default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare created public.reservations; transaction_status text;
begin
  if p_status not in ('pending', 'confirmed') or p_booking_source not in ('online', 'walk_in')
     or p_end_date <= p_start_date or p_guests_count < 1 or p_reserved_price < 0 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_BOOKING', 'message', 'Reservation details are invalid.');
  end if;
  if not exists (select 1 from public.rooms where id = p_room_id and capacity >= p_guests_count) then
    return jsonb_build_object('ok', false, 'code', 'INVALID_CAPACITY', 'message', 'Guest count exceeds room capacity.');
  end if;
  if p_booking_source = 'online' and (p_status <> 'pending' or p_payment_method <> 'paystack' or p_payment_reference is null) then
    return jsonb_build_object('ok', false, 'code', 'INVALID_PAYMENT', 'message', 'Online reservations require a Paystack payment hold.');
  end if;
  if p_booking_source = 'walk_in' and (p_status <> 'confirmed' or p_payment_method not in ('cash', 'momo_transfer', 'pos_card')) then
    return jsonb_build_object('ok', false, 'code', 'INVALID_PAYMENT', 'message', 'Walk-in reservations require a recorded front desk payment method.');
  end if;
  update public.reservations set status = 'expired', updated_at = now()
    where status = 'pending' and hold_expires_at <= now();
  begin
    insert into public.reservations
      (room_id, guest_id, guests_count, start_date, end_date, reserved_price,
       message, status, booking_source, hold_expires_at)
    values
      (p_room_id, p_guest_id, p_guests_count, p_start_date, p_end_date, p_reserved_price,
       coalesce(p_message, ''), p_status, p_booking_source,
       case when p_status = 'pending' then now() + interval '15 minutes' else null end)
    returning * into created;
  exception when exclusion_violation then
    return jsonb_build_object('ok', false, 'code', '23P01', 'message', 'Room is unavailable for these dates.');
  end;
  transaction_status := case when p_status = 'confirmed' then 'success' else 'pending' end;
  insert into public.reservation_transactions
    (reservation_id, provider, provider_reference, transaction_type, amount_minor,
     currency, method, recorded_by, status, paid_at)
  values
    (created.id, case when p_booking_source = 'online' then 'paystack' else 'manual' end,
     p_payment_reference, 'charge', round(p_reserved_price * 100)::bigint,
     coalesce(p_currency, 'GHS'), p_payment_method, p_recorded_by, transaction_status,
     case when transaction_status = 'success' then now() else null end);
  return jsonb_build_object('ok', true, 'reservation', to_jsonb(created));
end;
$$;
revoke all on function public.claim_room_reservation(bigint,bigint,integer,date,date,numeric,text,text,text,text,text,text,text) from public, anon, authenticated;
grant execute on function public.claim_room_reservation(bigint,bigint,integer,date,date,numeric,text,text,text,text,text,text,text) to service_role;

create or replace function public.confirm_paystack_reservation(
  p_reference text, p_amount_minor bigint, p_currency text,
  p_provider_transaction_id text, p_paid_at timestamptz
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare txn public.reservation_transactions; booking public.reservations;
begin
  select * into txn from public.reservation_transactions
    where provider_reference = p_reference and provider = 'paystack' and transaction_type = 'charge'
    for update;
  if not found or txn.amount_minor <> p_amount_minor or txn.currency <> p_currency then
    return jsonb_build_object('ok', false, 'code', 'PAYMENT_MISMATCH');
  end if;
  select * into booking from public.reservations where id = txn.reservation_id for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'RESERVATION_NOT_FOUND'); end if;
  update public.reservation_transactions set status = 'success',
    provider_transaction_id = coalesce(provider_transaction_id, p_provider_transaction_id),
    verified_at = coalesce(verified_at, now()), paid_at = coalesce(paid_at, p_paid_at, now()),
    updated_at = now() where id = txn.id;
  if booking.status = 'confirmed' then return jsonb_build_object('ok', true, 'reservation', to_jsonb(booking)); end if;
  if booking.status <> 'pending' or booking.hold_expires_at is null or booking.hold_expires_at <= now() then
    return jsonb_build_object('ok', false, 'code', 'HOLD_UNAVAILABLE', 'reservation_id', booking.id);
  end if;
  begin
    update public.reservations set status = 'confirmed', hold_expires_at = null, updated_at = now()
      where id = booking.id returning * into booking;
  exception when exclusion_violation then
    return jsonb_build_object('ok', false, 'code', 'HOLD_UNAVAILABLE', 'reservation_id', booking.id);
  end;
  return jsonb_build_object('ok', true, 'reservation', to_jsonb(booking));
end;
$$;
revoke all on function public.confirm_paystack_reservation(text,bigint,text,text,timestamptz) from public, anon, authenticated;
grant execute on function public.confirm_paystack_reservation(text,bigint,text,text,timestamptz) to service_role;

