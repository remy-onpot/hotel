create table if not exists public.gallery_images (
  id bigint generated by default as identity primary key,
  image_path text not null unique,
  title text not null default '',
  alt_text text not null,
  display_order integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint gallery_images_title_length check (char_length(title) <= 120),
  constraint gallery_images_alt_text_length check (char_length(alt_text) between 1 and 180),
  constraint gallery_images_display_order_nonnegative check (display_order >= 0)
);

create index if not exists gallery_images_public_order_idx
  on public.gallery_images (display_order, created_at)
  where is_published;

alter table public.gallery_images enable row level security;

grant select on public.gallery_images to anon, authenticated;

drop policy if exists "Published gallery images are public" on public.gallery_images;
create policy "Published gallery images are public"
  on public.gallery_images for select
  to anon, authenticated
  using (is_published);
