-- A durable staff queue for successful Paystack charges that could not be
-- matched to an active room hold. This records follow-up; it does not refund.
create table if not exists public.payment_exceptions (
  id bigint generated by default as identity primary key,
  payment_reference text not null unique,
  reservation_id bigint references public.reservations(id) on delete set null,
  paid_amount_minor bigint,
  currency text not null default 'GHS',
  reason text not null,
  status text not null default 'open'
    check (status in ('open', 'refund_initiated', 'refunded', 'closed')),
  resolution_note text not null default '',
  provider_refund_reference text,
  resolved_by text,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.payment_exceptions enable row level security;
revoke all on public.payment_exceptions from anon, authenticated;
grant all on public.payment_exceptions to service_role;

-- Contact messages are an admin-managed queue. Rate limiting is serialized
-- per normalized email so parallel submissions cannot evade the hourly cap.
alter table public.inbox add column if not exists status text not null default 'new'
  check (status in ('new', 'in_progress', 'resolved'));
alter table public.inbox add column if not exists updated_at timestamptz not null default now();
revoke insert on public.inbox from anon, authenticated;

create or replace function public.submit_contact_message(
  p_fullname text,
  p_email text,
  p_phone text,
  p_message text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  normalized_email text := lower(trim(p_email));
  created_id bigint;
begin
  if length(trim(p_fullname)) not between 3 and 64
     or length(normalized_email) > 254
     or normalized_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
     or length(trim(p_phone)) not between 7 and 32
     or length(trim(p_message)) not between 20 and 500 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_MESSAGE');
  end if;

  perform pg_advisory_xact_lock(hashtextextended(normalized_email, 0));
  if (select count(*) from public.inbox i
      where lower(i.email) = normalized_email and i.created_at > now() - interval '1 hour') >= 3 then
    return jsonb_build_object('ok', false, 'code', 'RATE_LIMITED');
  end if;

  insert into public.inbox(fullname, email, phone, message)
  values (trim(p_fullname), normalized_email, trim(p_phone), trim(p_message))
  returning id into created_id;
  return jsonb_build_object('ok', true, 'id', created_id);
end;
$$;
revoke all on function public.submit_contact_message(text,text,text,text) from public, anon, authenticated;
grant execute on function public.submit_contact_message(text,text,text,text) to service_role;

