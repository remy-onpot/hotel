-- Initial database schema for the hotel booking application.
-- Apply with `supabase db push` or paste into the Supabase SQL editor.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  thumbnail text not null,
  price numeric(10, 2) not null check (price >= 0),
  capacity integer not null check (capacity > 0),
  sleeps integer not null default 1 check (sleeps > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.room_images (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.rooms(id) on delete cascade,
  img_path text not null,
  created_at timestamptz not null default now(),
  unique (room_id, img_path)
);
create index if not exists room_images_room_id_idx on public.room_images(room_id);

create table if not exists public.guests (
  id bigint generated by default as identity primary key,
  fullname text not null,
  email text not null,
  password text not null default '',
  avatar text not null default '',
  phone text not null default '',
  nationality text not null default '',
  "countryFlag" text not null default '',
  "nationalID" text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint guests_email_unique unique (email)
);
create unique index if not exists guests_email_lower_unique on public.guests (lower(email));

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.rooms(id) on delete restrict,
  guest_id bigint not null references public.guests(id) on delete restrict,
  guests_count integer not null check (guests_count > 0),
  message text not null default '',
  reserved_price numeric(10, 2) not null check (reserved_price >= 0),
  currency text not null default 'GHS',
  start_date date not null,
  end_date date not null,
  stripe_session_id text unique,
  payment_provider text,
  payment_reference text,
  status text not null default 'unconfirmed'
    check (status in ('unconfirmed', 'pending', 'confirmed', 'cancelled', 'canceled', 'finished')),
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reservations_valid_dates check (end_date > start_date)
);
create index if not exists reservations_room_dates_idx on public.reservations(room_id, start_date, end_date);
create index if not exists reservations_guest_id_idx on public.reservations(guest_id);
create index if not exists reservations_confirmed_room_dates_idx
  on public.reservations(room_id, start_date, end_date)
  where status = 'confirmed' and deleted_at is null;

create table if not exists public.inbox (
  id bigint generated by default as identity primary key,
  fullname text not null,
  email text not null,
  phone text not null default '',
  message text not null,
  created_at timestamptz not null default now()
);

-- Password hashes are never selected by the guest lookup API.
create or replace view public.guests_view
  with (security_invoker = true)
as
select id, email, "nationalID", nationality, "countryFlag", fullname, phone, created_at, avatar
from public.guests;

-- Resolve the guest associated with the email claim in the app's Supabase JWT.
create or replace function public.current_guest_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select g.id from public.guests as g
  where lower(g.email) = lower(auth.jwt() ->> 'email')
  limit 1
$$;
revoke all on function public.current_guest_id() from public, anon;
grant execute on function public.current_guest_id() to authenticated;

alter table public.rooms enable row level security;
alter table public.room_images enable row level security;
alter table public.guests enable row level security;
alter table public.reservations enable row level security;
alter table public.inbox enable row level security;

drop policy if exists "rooms are publicly readable" on public.rooms;
create policy "rooms are publicly readable" on public.rooms
  for select to anon, authenticated using (true);
drop policy if exists "room images are publicly readable" on public.room_images;
create policy "room images are publicly readable" on public.room_images
  for select to anon, authenticated using (true);

drop policy if exists "guests can read their own profile" on public.guests;
create policy "guests can read their own profile" on public.guests
  for select to authenticated using (id = (select public.current_guest_id()));
drop policy if exists "guests can update their own profile" on public.guests;
create policy "guests can update their own profile" on public.guests
  for update to authenticated
  using (id = (select public.current_guest_id()))
  with check (id = (select public.current_guest_id()));

drop policy if exists "guests can read their reservations" on public.reservations;
create policy "guests can read their reservations" on public.reservations
  for select to authenticated using (guest_id = (select public.current_guest_id()));
drop policy if exists "guests can create their reservations" on public.reservations;
create policy "guests can create their reservations" on public.reservations
  for insert to authenticated
  with check (guest_id = (select public.current_guest_id()));
drop policy if exists "guests can update their reservations" on public.reservations;
create policy "guests can update their reservations" on public.reservations
  for update to authenticated
  using (guest_id = (select public.current_guest_id()))
  with check (guest_id = (select public.current_guest_id()));

-- Anonymous availability and payment lookups need a limited row shape only.
grant select (id, room_id, start_date, end_date, status)
  on public.reservations to anon;
drop policy if exists "confirmed reservations are publicly readable" on public.reservations;
create policy "confirmed reservations are publicly readable" on public.reservations
  for select to anon using (status = 'confirmed' and deleted_at is null);

grant usage on schema public to anon, authenticated, service_role;
grant select on public.rooms, public.room_images to anon, authenticated;
grant select on public.guests_view to anon, authenticated, service_role;
grant select, insert, update on public.guests to authenticated;
grant select, insert, update on public.reservations to authenticated;
grant insert, select on public.inbox to anon, authenticated;
grant all on public.rooms, public.room_images, public.guests, public.reservations, public.inbox to service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;

-- Auth.js SupabaseAdapter's default OAuth storage schema.
create schema if not exists next_auth;
grant usage on schema next_auth to service_role;

create table if not exists next_auth.users (
  id uuid not null default gen_random_uuid() primary key,
  name text,
  email text unique,
  "emailVerified" timestamptz,
  image text
);
create table if not exists next_auth.accounts (
  id uuid not null default gen_random_uuid() primary key,
  type text not null,
  provider text not null,
  "providerAccountId" text not null,
  refresh_token text,
  access_token text,
  expires_at bigint,
  token_type text,
  scope text,
  id_token text,
  session_state text,
  oauth_token_secret text,
  oauth_token text,
  "userId" uuid not null references next_auth.users(id) on delete cascade,
  unique (provider, "providerAccountId")
);
create table if not exists next_auth.sessions (
  id uuid not null default gen_random_uuid() primary key,
  expires timestamptz not null,
  "sessionToken" text not null unique,
  "userId" uuid not null references next_auth.users(id) on delete cascade
);
create table if not exists next_auth.verification_tokens (
  id bigint generated by default as identity primary key,
  identifier text not null,
  expires timestamptz not null,
  token text not null unique,
  unique (identifier, token)
);
grant all on all tables in schema next_auth to service_role;
grant all on all sequences in schema next_auth to service_role;
